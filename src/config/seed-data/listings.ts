var galleryCursor = 0;
function gallery(featured, extra, n = undefined) {
  var list = [featured].concat(extra || []);
  var pool = INTERIORS.filter(function (x) {
    return list.indexOf(x) < 0;
  });
  while (list.length < (n || 5)) {
    list.push(pool[galleryCursor % pool.length]);
    galleryCursor += 3;
    pool = INTERIORS.filter(function (x) {
      return list.indexOf(x) < 0;
    });
  }
  return list.map(function (name, i) {
    return { src: im(name), caption: i === 0 ? '' : CAPTIONS[name] || '' };
  });
}
